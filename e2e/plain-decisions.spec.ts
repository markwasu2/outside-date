import {test,expect} from '@playwright/test';
test('first month explains role, goal, limit and consequence before reserving an action',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Tutorial',exact:true}).click();
 const count=page.getByTestId('actions-remaining'),help=page.getByTestId('monthly-decisions-help');
 await expect(count).toHaveText('Focus this month: 6 of 6 left');
 await expect(help).toHaveCount(0);await count.click();
 await expect(help).toContainText('limited time and attention');await expect(help).toContainText('unused focus does not carry over');await expect(help).toContainText('Goal:');
 await page.screenshot({path:'docs/screenshots/cold2/monthly-decisions-intro.png'});
 await page.setViewportSize({width:1440,height:900});await page.screenshot({path:'docs/screenshots/cold2/monthly-decisions-1440.png'});await page.setViewportSize({width:1280,height:720});
 await page.getByRole('button',{name:'Start planning',exact:true}).click();await expect(help).toHaveCount(0);
 await page.locator('[data-campus-object="substation"]').click();const study=page.getByTestId('popover-action').filter({hasText:'Commission the interconnection study'});
 await expect(study).toContainText('Uses 2 focus points');await expect(study).toContainText('does not give you power immediately');
 await page.screenshot({path:'docs/screenshots/cold2/monthly-decision-preview.png'});
 await study.click();await expect(count).toHaveText('Focus this month: 4 of 6 left');
 await page.getByTestId('map-popover').getByRole('button',{name:'Close',exact:true}).click();
 await page.getByRole('button',{name:'Plan',exact:true}).click();await page.getByRole('button',{name:'remove',exact:true}).click();await expect(count).toHaveText('Focus this month: 6 of 6 left');
 await page.getByRole('button',{name:'Close panel',exact:true}).click();
 await page.getByRole('button',{name:'End month',exact:true}).click();await expect(count).toHaveText('Focus this month: 6 of 6 left');
 await count.click();await expect(help).toBeVisible();
});
